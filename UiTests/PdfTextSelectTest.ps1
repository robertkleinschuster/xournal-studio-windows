# The mouse selects the PDF's text: a generated one-page PDF full of lines of one long word ("Spannungsteilerberechnung",
# no spaces, so a double click anywhere on a line selects exactly that word) is opened as a document. A double click on
# a line selects the word, Strg+C puts it on the clipboard as text; a mouse drag along the line selects part of it (a
# piece of the word on the clipboard); Escape clears the selection. A pen stroke over the text, then a mouse drag that
# starts on that ink makes an ink selection (lasso), not a text selection. Checked in the app's logs and the clipboard.
# The PDF is generated by the test (no data files beyond the default ones).
#   UiTests\Run-AppTest.ps1 -Test UiTests\PdfTextSelectTest.ps1 -Extra <uiaprobe.exe>
. C:\sbx\TestKit.ps1
Add-Type -AssemblyName System.Windows.Forms

$Word = 'Spannungsteilerberechnung'

function Ctrl($k, $label) { [Inj]::Ctrl($k); Start-Sleep -Milliseconds 1200; "ctrl+$label" }
function LogCount($file, $pattern) { if (Test-Path $file) { @(Get-Content $file | Where-Object { $_ -match $pattern }).Count } else { 0 } }
function AppCount($pattern) { LogCount "$out\app.log" $pattern }
function InkCount($pattern) { LogCount "$out\app.log.inkpages.log" $pattern }
function Expect($pattern, $what, $times = 1) {
    for ($i = 0; $i -lt 20 -and (AppCount $pattern) -lt $times; $i++) { Start-Sleep -Milliseconds 500 }
    if ((AppCount $pattern) -lt $times) { throw "not in the log ($times x): $what ($pattern)" }
    "ok: $what"
}
function ClipboardText {
    for ($i = 0; $i -lt 5; $i++) {
        try { return [Windows.Forms.Clipboard]::GetText() } catch { "clipboard busy: $($_.Exception.Message)" | Out-Host; Start-Sleep -Milliseconds 300 }
    }
    throw 'the clipboard cannot be read'
}

# A PDF written by hand: objects, then the cross-reference table with their byte offsets.
function New-TestPdf($file) {
    $content = ''
    for ($y = 770; $y -ge 30; $y -= 26) { $content += "BT /F1 26 Tf 60 $y Td ($Word) Tj ET`n" }
    $objects = @(
        '<< /Type /Catalog /Pages 2 0 R >>',
        '<< /Type /Pages /Kids [3 0 R] /Count 1 >>',
        '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Resources << /Font << /F1 5 0 R >> >> /Contents 4 0 R >>',
        "<< /Length $($content.Length) >>`nstream`n$content`nendstream",
        '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>'
    )
    $text = "%PDF-1.4`n"
    $offsets = @()
    for ($i = 0; $i -lt $objects.Count; $i++) {
        $offsets += [Text.Encoding]::ASCII.GetByteCount($text)
        $text += "$($i + 1) 0 obj`n$($objects[$i])`nendobj`n"
    }
    $xref = [Text.Encoding]::ASCII.GetByteCount($text)
    $text += "xref`n0 $($objects.Count + 1)`n0000000000 65535 f `n"
    foreach ($o in $offsets) { $text += ('{0:D10} 00000 n ' -f $o) + "`n" }
    $text += "trailer`n<< /Size $($objects.Count + 1) /Root 1 0 R >>`nstartxref`n$xref`n%%EOF`n"
    [IO.File]::WriteAllBytes($file, [Text.Encoding]::ASCII.GetBytes($text))
}

$INRANGE = 0x2; $INCONTACT = 0x4; $FIRST = 0x10; $PRIMARY = 0x2000; $DOWN = 0x10000; $UPDATE = 0x20000; $UP = 0x40000
# A pen stroke between client DIPs; hovers ~120 ms before it touches, as a real pen.
function Stroke($x0, $y0, $x1, $y1) {
    for ($i = 0; $i -lt 15; $i++) { [Inj]::PenFrame($x0, $y0, $INRANGE -bor $UPDATE -bor $PRIMARY, 0, 0) }
    [Inj]::PenFrame($x0, $y0, $INRANGE -bor $INCONTACT -bor $DOWN -bor $FIRST -bor $PRIMARY, 0, 600)
    $n = [Math]::Max(1, [int]([Math]::Sqrt(($x1 - $x0) * ($x1 - $x0) + ($y1 - $y0) * ($y1 - $y0)) / 4))
    for ($s = 1; $s -le $n; $s++) {
        [Inj]::PenFrame($x0 + ($x1 - $x0) * $s / $n, $y0 + ($y1 - $y0) * $s / $n, $INRANGE -bor $INCONTACT -bor $UPDATE -bor $FIRST -bor $PRIMARY, 0, 600)
    }
    [Inj]::PenFrame($x1, $y1, $INRANGE -bor $UP -bor $PRIMARY, 0, 0)
    [Inj]::PenFrame($x1, $y1, $UPDATE -bor $PRIMARY, 0, 0)
    Start-Sleep -Milliseconds 700
    "stroke: $x0,$y0 -> $x1,$y1"
}

Invoke-Test {
    New-Item -ItemType Directory -Force C:\work | Out-Null
    New-TestPdf 'C:\work\Text.pdf'
    $env:XOURNAL_STUDIO_CONFIG_DIR = "$out\config"
    $env:XOURNAL_STUDIO_LOG = "$out\app.log"
    Start-TestApp 'XournalStudio.exe' '"C:\work\Text.pdf"'
    Start-Sleep 3
    Expect 'pdf text selection: the PDF''s text is ready' 'the PDF''s text is read'
    [Inj]::MoveMouse(500, 300)
    Shot '01-opened'

    # 1. A double click on a line selects its word (lines are 26 units apart: the first y where the press meets a
    #    glyph's box is taken).
    $x = 0.45 * [Inj]::W
    $lineY = $null
    $selections = AppCount 'pdf text selection: \d+ characters on page'
    for ($y = 0.4 * [Inj]::H; $y -lt 0.4 * [Inj]::H + 60 -and -not $lineY; $y += 4) {
        [Inj]::Click($x, $y); [Inj]::Click($x, $y); Start-Sleep -Milliseconds 800
        if ((AppCount 'pdf text selection: \d+ characters on page') -gt $selections) { $lineY = $y }
    }
    if (-not $lineY) { throw 'no double click selected the PDF''s text' }
    "double click at $x,$lineY selected"
    Expect "pdf text selection: $($Word.Length) characters on page 1" 'the double click selected the whole word'
    Shot '02-word-selected'
    Ctrl 0x43 'C'
    Expect 'pdf text selection: \d+ characters copied' 'Strg+C copied the PDF''s text'
    $copied = ClipboardText
    "clipboard: '$copied'"
    if ($copied -ne $Word) { throw "the clipboard holds '$copied', not '$Word'" }

    # 2. Escape clears it; a mouse drag along the line selects a piece of the word.
    [Inj]::Key(0x1B); Start-Sleep -Milliseconds 600
    Shot '03-cleared'
    $before = AppCount 'pdf text selection: \d+ characters on page'
    [Inj]::MouseDrag((L ($x - 60) $lineY ($x + 60) $lineY)); Start-Sleep -Milliseconds 800
    if ((AppCount 'pdf text selection: \d+ characters on page') -le $before) { throw 'the mouse drag selected no text' }
    Shot '04-drag-selected'
    Ctrl 0x43 'C'
    $piece = ClipboardText
    "clipboard: '$piece'"
    if ($piece.Length -lt 3 -or -not $Word.Contains($piece) -or $piece -eq $Word) { throw "the drag copied '$piece', not a piece of '$Word'" }
    if ((InkCount 'mouse: selection drag begins') -gt 0) { throw 'a drag on the PDF''s text made a lasso' }

    # 3. A left drag selects PDF text through ink. A right drag lassos the ink.
    [Inj]::Key(0x1B); Start-Sleep -Milliseconds 400
    Stroke ($x - 150) $lineY ($x + 150) $lineY
    Shot '05-ink-over-text'
    $texts = AppCount 'pdf text selection: \d+ characters on page'
    [Inj]::MouseDrag((L $x $lineY ($x + 60) $lineY)); Start-Sleep -Milliseconds 800
    if ((AppCount 'pdf text selection: \d+ characters on page') -le $texts) { throw 'the text under the ink was not selected' }
    [Inj]::Key(0x1B); Start-Sleep -Milliseconds 400
    $texts = AppCount 'pdf text selection: \d+ characters on page'
    [Inj]::RightMouseDrag((L $x $lineY ($x + 40) ($lineY + 80) ($x - 200) ($lineY + 80) ($x - 200) ($lineY - 40) ($x + 200) ($lineY - 40))); Start-Sleep -Milliseconds 1200
    Shot '06-ink-selected'
    if ((InkCount 'mouse: selection drag begins') -lt 1) { throw 'the drag on ink made no lasso' }
    if ((AppCount 'pdf text selection: \d+ characters on page') -ne $texts) { throw 'the drag on ink selected the PDF''s text' }
    'pdf text selection: passed'
}
